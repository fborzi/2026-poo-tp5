
package com.francoborzi.modulos.ejercicio2508.config;

import com.francoborzi.modulos.ejercicio2508.exception.DAOException;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Configura la conexion JDBC con H2.
 */
public final class DatabaseConfig {

    private static final Path DIRECTORIO = Path.of("var", "data");

    private static final String URL =
            "jdbc:h2:file:./var/data/productos";

    private DatabaseConfig() {
    }

    /**
     * Obtiene una nueva conexion a la base de datos.
     *
     * @return conexion JDBC
     * @throws DAOException si falla la conexion
     */
    public static Connection getConnection() throws DAOException {
        try {
            Files.createDirectories(DIRECTORIO);
            return DriverManager.getConnection(URL, "sa", "");
        } catch (IOException | SQLException excepcion) {
            throw new DAOException(
                    "No se pudo conectar con la base de datos",
                    excepcion);
        }
    }

    /**
     * Crea la tabla de productos si no existe.
     *
     * @throws DAOException si falla la inicializacion
     */
    public static void inicializar() throws DAOException {
        String sql = """
                CREATE TABLE IF NOT EXISTS productos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    codigo_sku VARCHAR(100) NOT NULL UNIQUE,
                    descripcion VARCHAR(255) NOT NULL,
                    precio_unitario DECIMAL(15, 2) NOT NULL,
                    stock_disponible INT NOT NULL,
                    CONSTRAINT chk_precio CHECK (precio_unitario >= 0),
                    CONSTRAINT chk_stock CHECK (stock_disponible >= 0)
                )
                """;

        try (Connection conexion = getConnection();
             Statement sentencia = conexion.createStatement()) {
            sentencia.execute(sql);
        } catch (SQLException excepcion) {
            throw new DAOException(
                    "No se pudo crear la tabla de productos",
                    excepcion);
        }
    }
}
